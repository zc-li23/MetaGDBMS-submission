/**
 * @brief: L5 interaction layer contract, defining a unified access model for
 *         multiple query languages.
 */

/**
 * @brief: Query language enumeration, supporting Cypher, ISO-GQL, Gremlin, and
 *         custom extension languages.
 */
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum QueryLanguage {
    Cypher,
    Gql,
    Gremlin,
    Custom(String),
}

/**
 * @brief: Top-level query request wrapper, containing source text and the language
 *         used.
 */
#[derive(Debug, Clone)]
pub struct QueryRequest {
    pub language: QueryLanguage,
    pub source: String,
}

/**
 * @brief: Interaction layer frontend interface, responsible for declaring supported
 *         languages and encapsulating request form.
 */
pub trait Frontend: Send + Sync {
    /**
     * @brief: Get the query language type handled by the current frontend.
     * @return: A QueryLanguage enum value.
     */
    fn language(&self) -> QueryLanguage;

    /**
     * @brief: Construct a standard request object for the given query text.
     * @param src: The raw query source string.
     * @return: A wrapped QueryRequest.
     */
    fn make_request(&self, src: &str) -> QueryRequest {
        QueryRequest {
            language: self.language(),
            source: src.to_string(),
        }
    }
}

/**
 * @brief: Generic language frontend, parameterized by QueryLanguage.
 *
 * The framework can register any language via
 * `LanguageFrontend::new(QueryLanguage::Cypher)`.
 */
#[derive(Clone)]
pub struct LanguageFrontend {
    language: QueryLanguage,
}

impl LanguageFrontend {
    /**
     * @brief: Construct a generic frontend for the specified language.
     * @param language: The query language type.
     * @return: A LanguageFrontend instance.
     */
    pub fn new(language: QueryLanguage) -> Self {
        Self { language }
    }
}

impl Frontend for LanguageFrontend {
    /**
     * @brief: Declare the supported query language.
     * @return: A QueryLanguage enum value.
     */
    fn language(&self) -> QueryLanguage {
        self.language.clone()
    }
}

